"""
check_supabase.py - Diagnostic tool to verify your Supabase connection and table setup.
"""

import os
import sys
from dotenv import load_dotenv

load_dotenv()


def test_connection():
    supabase_url = os.getenv("SUPABASE_URL")
    supabase_key = os.getenv("SUPABASE_KEY")

    print("=" * 60)
    print("🔍 Testing Supabase Connection...")
    print("=" * 60)

    if not supabase_url or "your-project-id" in supabase_url:
        print("❌ Error: SUPABASE_URL is missing or still has placeholder values in .env")
        print("   Please open .env and set your real Supabase Project URL.")
        return False

    if not supabase_key or "your-supabase" in supabase_key:
        print("❌ Error: SUPABASE_KEY is missing or still has placeholder values in .env")
        print("   Please open .env and set your real Supabase anon or service_role key.")
        return False

    cleaned_url = supabase_url.strip().rstrip("/")
    if cleaned_url.endswith("/rest/v1"):
        cleaned_url = cleaned_url[:-len("/rest/v1")].rstrip("/")

    print(f"Connecting to: {cleaned_url}")

    try:
        from supabase import create_client
        client = create_client(cleaned_url, supabase_key)
        print("✅ Supabase client initialized.")
    except Exception as e:
        print(f"❌ Failed to initialize Supabase client: {e}")
        return False

    # Check applications table
    try:
        res = client.table("applications").select("id").limit(1).execute()
        print("✅ Successfully queried 'applications' table!")
        print(f"   Current record count check returned: {len(res.data)} sample rows.")
        print("\n🎉 Your Supabase database is connected and ready to use!")
        return True
    except Exception as e:
        print(f"⚠️ Warning: Could not query 'applications' table: {e}")
        print("\n👉 Did you run the SQL migration query in the Supabase SQL Editor?")
        print("   Go to: Supabase Dashboard -> SQL Editor -> New Query -> Run this:")
        print("""
CREATE TABLE IF NOT EXISTS applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_url TEXT UNIQUE NOT NULL,
    company TEXT NOT NULL,
    title TEXT NOT NULL,
    status TEXT NOT NULL,
    match_score INTEGER,
    timestamp TIMESTAMPTZ DEFAULT NOW(),
    metadata JSONB DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS idx_applications_job_url ON applications(job_url);
CREATE INDEX IF NOT EXISTS idx_applications_status ON applications(status);
        """)
        return False


if __name__ == "__main__":
    success = test_connection()
    sys.exit(0 if success else 1)
