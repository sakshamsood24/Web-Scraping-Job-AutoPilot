"""
db.py - Database Layer for Job Autopilot Pipeline
Connects to Supabase PostgreSQL to record processed applications, track status,
and prevent duplicate applications.
"""

import os
import logging
from datetime import datetime, timezone
from typing import Optional, Dict, Any
from dotenv import load_dotenv

# Load environment variables
load_dotenv()

logger = logging.getLogger("JobAutopilot.DB")

# Lazy-loaded client singleton
_supabase_client = None

SUPABASE_TABLE_NAME = "applications"

SUPABASE_SCHEMA_SQL = """
-- Supabase SQL to initialize the applications tracking table
CREATE TABLE IF NOT EXISTS applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_url TEXT UNIQUE NOT NULL,
    company TEXT NOT NULL,
    title TEXT NOT NULL,
    status TEXT NOT NULL,
    match_score INTEGER,
    timestamp TIMESTAMPTZ DEFAULT NOW(),
    metadata JSONB DEFAULT '{}'::jsonb
);

-- Index for rapid lookup when checking if already applied
CREATE INDEX IF NOT EXISTS idx_applications_job_url ON applications(job_url);
CREATE INDEX IF NOT EXISTS idx_applications_status ON applications(status);
"""


def get_supabase_client():
    """
    Initializes and returns the Supabase client using environment variables.
    Raises ValueError if required credentials are missing.
    """
    global _supabase_client
    if _supabase_client is not None:
        return _supabase_client

    supabase_url = os.getenv("SUPABASE_URL")
    supabase_key = os.getenv("SUPABASE_KEY")

    if not supabase_url or not supabase_key:
        logger.warning(
            "SUPABASE_URL or SUPABASE_KEY not found in environment. "
            "Database operations will run in local mock/fallback mode."
        )
        return None

    # Strip /rest/v1 or trailing slashes if present
    cleaned_url = supabase_url.strip().rstrip("/")
    if cleaned_url.endswith("/rest/v1"):
        cleaned_url = cleaned_url[:-len("/rest/v1")].rstrip("/")

    try:
        from supabase import create_client, Client
        _supabase_client = create_client(cleaned_url, supabase_key)
        logger.info(f"Connected successfully to Supabase at: {cleaned_url}")
        return _supabase_client
    except Exception as e:
        logger.error(f"Failed to initialize Supabase client: {e}")
        return None


# Local memory fallback set to prevent duplicate attempts if Supabase is temporarily unreachable
_local_url_cache: set[str] = set()


def get_all_applied_urls() -> set[str]:
    """
    Fetches all recorded job URLs from Supabase in a single batch query.
    Used for lightning-fast O(1) in-memory deduplication during discovery loops.
    """
    client = get_supabase_client()
    urls = set(_local_url_cache)
    if client is None:
        return urls

    try:
        response = client.table(SUPABASE_TABLE_NAME).select("job_url").execute()
        if response.data:
            for item in response.data:
                u = item.get("job_url")
                if u:
                    urls.add(u)
                    _local_url_cache.add(u)
        logger.info(f"Loaded {len(urls)} previously processed job URLs from Supabase for fast deduplication.")
    except Exception as e:
        logger.error(f"Error fetching all applied URLs from Supabase: {e}")
    return urls


def is_already_applied(job_url: str, known_urls: Optional[set[str]] = None) -> bool:
    """
    Checks if a job URL has already been recorded in the applications table.
    
    Args:
        job_url: The canonical URL of the job posting.
        known_urls: Optional pre-fetched set of applied URLs for O(1) lookup.
        
    Returns:
        bool: True if application exists, False otherwise.
    """
    if not job_url:
        return False

    if known_urls is not None:
        return job_url in known_urls

    if job_url in _local_url_cache:
        return True

    client = get_supabase_client()
    if client is None:
        return False

    try:
        response = (
            client.table(SUPABASE_TABLE_NAME)
            .select("id, status")
            .eq("job_url", job_url)
            .limit(1)
            .execute()
        )
        exists = bool(response.data and len(response.data) > 0)
        if exists:
            _local_url_cache.add(job_url)
        logger.debug(f"[Supabase] is_already_applied({job_url}) -> {exists}")
        return exists
    except Exception as e:
        logger.error(f"Error querying Supabase for job_url '{job_url}': {e}. Falling back to memory cache.")
        return job_url in _local_url_cache


def log_application(
    job_url: str,
    company: str,
    title: str,
    status: str,
    match_score: Optional[int] = None,
    metadata: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """
    Logs or updates an application record in Supabase.
    
    Args:
        job_url: The unique URL of the job posting.
        company: Company name.
        title: Job title.
        status: Application status ('discovered', 'skipped_low_match', 'skipped_not_remote', 'drafted', 'applied', 'failed').
        match_score: Compatibility score evaluated by LLM (0-100).
        metadata: Optional dictionary with custom responses, screenshot paths, errors, etc.
        
    Returns:
        Dict: Result containing status and inserted/cached data.
    """
    now_iso = datetime.now(timezone.utc).isoformat()
    record = {
        "job_url": job_url,
        "company": company,
        "title": title,
        "status": status,
        "match_score": match_score,
        "timestamp": now_iso,
        "metadata": metadata or {},
    }

    client = get_supabase_client()
    if client is None:
        # Save to local cache
        _local_url_cache.add(job_url)
        logger.info(f"[Local Cache] Logged application for '{title}' at '{company}' with status='{status}'")
        return {"success": True, "mode": "local_cache", "data": record}

    try:
        # Upsert by job_url to handle status changes gracefully (e.g. from discovered to drafted)
        response = (
            client.table(SUPABASE_TABLE_NAME)
            .upsert(record, on_conflict="job_url")
            .execute()
        )
        _local_url_cache.add(job_url)
        logger.info(f"[Supabase] Successfully logged '{title}' ({company}) - status: {status}, score: {match_score}")
        return {"success": True, "mode": "supabase", "data": response.data}
    except Exception as e:
        logger.error(f"[Supabase] Failed to log application to Supabase: {e}")
        _local_url_cache.add(job_url)
        return {"success": False, "error": str(e), "data": record}


def get_application(job_url: str) -> Optional[Dict[str, Any]]:
    """
    Retrieves the stored record for a given job URL.
    """
    client = get_supabase_client()
    if client is None:
        return None

    try:
        response = (
            client.table(SUPABASE_TABLE_NAME)
            .select("*")
            .eq("job_url", job_url)
            .limit(1)
            .execute()
        )
        if response.data:
            return response.data[0]
        return None
    except Exception as e:
        logger.error(f"Error fetching application for '{job_url}': {e}")
        return None
